/**
 * 根据维度 key 和分数返回语义标签信息
 * @param {'fn'|'r'|'kn'|'fs'|'eh'} key
 * @param {number} score 1–5
 * @returns {{ label: string, note?: string, barColor: string, dimColor: string }}
 */
function dimInfo(key, score) {
  const s = Math.max(1, Math.min(5, Math.round(score)));
  switch (key) {
    case 'fn':
      return {
        label: ['严重占比', '较为重要', '重要但非必要', '较为闲置', '完全闲置'][s - 1],
        barColor: '#4A7FC1',
        dimColor: '#3A6AA8',
      };
    case 'r':
      return {
        label: ['高度焦虑', '情绪脆弱', '理性克制', '心理稳健', '稳如磐石'][s - 1],
        barColor: '#cc9010',
        dimColor: '#a87108',
      };
    case 'kn':
      return {
        label: ['几乎不了解', '初步了解', '基本理解', '较为了解', '深度理解'][s - 1],
        barColor: '#3ca06c',
        dimColor: '#1e7d50',
      };
    case 'fs':
      return {
        label: ['一次性投入', '偶尔有补仓', '混合型', '有持续来源', '持续流入'][s - 1],
        barColor: '#3ca06c',
        dimColor: '#1e7d50',
      };
    case 'eh': {
      const items = [
        { label: '偏短期',   note: '目标1年内看到结果' },
        { label: '偏中短期', note: '目标1–3年内看到结果' },
        { label: '中期',     note: '目标3–5年内看到结果' },
        { label: '中长期',   note: '目标5–10年规划' },
        { label: '长期主义', note: '10年以上布局' },
      ];
      return { ...items[s - 1], barColor: '#cc9010', dimColor: '#a87108' };
    }
    default:
      return { label: '—', barColor: '#aeaaa4', dimColor: '#7c7870' };
  }
}

/**
 * 根据得分生成头部展示标签（取前4个最具代表性维度的语义标签）
 * @param {{ fn, r, kn, fs, eh }} scores
 * @returns {string[]}
 */
function getDimTags(scores) {
  const dims = [
    { key: 'fn', score: scores.fn },
    { key: 'r',  score: scores.r  },
    { key: 'kn', score: scores.kn },
    { key: 'fs', score: scores.fs },
    { key: 'eh', score: scores.eh },
  ];
  // Sort by score desc, take top 4
  return dims
    .sort((a, b) => b.score - a.score)
    .slice(0, 4)
    .map(d => dimInfo(d.key, d.score).label);
}

