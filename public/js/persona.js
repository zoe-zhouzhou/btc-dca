/* ═══════════════════════════════════════
   欧氏距离最近邻匹配
   @param {object} scores — { fn, r, kn, fs, eh }
   @returns {string} personaKey
═══════════════════════════════════════ */
function matchPersona(scores) {
  let bestKey  = null;
  let bestDist = Infinity;

  for (const [key, c] of Object.entries(PERSONA_CENTROIDS)) {
    const dist = Math.sqrt(
      Math.pow(scores.fn - c.fn, 2) +
      Math.pow(scores.r  - c.r,  2) +
      Math.pow(scores.kn - c.kn, 2) +
      Math.pow(scores.fs - c.fs, 2) +
      Math.pow(scores.eh - c.eh, 2)
    );
    if (dist < bestDist) {
      bestDist = dist;
      bestKey  = key;
    }
  }

  return bestKey;
}

/* ═══════════════════════════════════════
   从 URL 参数或 localStorage 读取得分
   @returns {{ fn, r, kn, fs, eh } | null}
═══════════════════════════════════════ */
function readScores() {
  /* 优先 URL 参数 */
  const params = new URLSearchParams(location.search);
  const fn = parseInt(params.get('fn'));
  const r  = parseInt(params.get('r'));
  const kn = parseInt(params.get('kn'));
  const fs = parseInt(params.get('fs'));
  const eh = parseInt(params.get('eh'));

  if ([fn, r, kn, fs, eh].every(v => v >= 1 && v <= 5)) {
    return { fn, r, kn, fs, eh };
  }

  /* 回退 localStorage */
  try {
    const saved = localStorage.getItem('btc_dca_scores');
    if (saved) {
      const s = JSON.parse(saved);
      if (s.fund_nature && s.resilience) {
        return {
          fn: s.fund_nature,
          r:  s.resilience,
          kn: s.knowledge,
          fs: s.fund_structure,
          eh: s.exit_horizon,
        };
      }
    }
  } catch (_) { /* ignore */ }

  return null;
}
